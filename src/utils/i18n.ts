export interface LanguageMeta {
	/** BCP-47 语言代码，与 UI_TRANSLATIONS 的键一致，如 'zh-TW'。 */
	code: string;
	label: string;
	englishName: string;
	flag: string;
	/** 顶栏语言按钮上显示的缩写。 */
	shortCode: string;
	/** 该语言在 URL 中的目录前缀，root（简体中文）为空字符串。 */
	dir: string;
}

